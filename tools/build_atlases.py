#!/usr/bin/env python3
"""Packs many small sprites into a few atlas PNGs so the game uploads 2-3 textures
instead of ~55 (Kaboom re-uploads its whole 2048x2048 atlas canvas for EVERY loadSprite,
which is what made the loading bar stutter). Re-run this if you add/replace a flag or
small sprite, then commit sprites/atlas_*.png and src/atlas_data.js.

    python3 tools/build_atlases.py        (needs: pip install pillow numpy)
"""
import json, os, numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GUTTER = 2  # edge-extruded padding so scaled sprites never bleed into a neighbour

def extrude(im):
    a = np.array(im.convert("RGBA"))
    a = np.pad(a, ((GUTTER, GUTTER), (GUTTER, GUTTER), (0, 0)), mode="edge")
    return Image.fromarray(a)

def pack(items, max_w, out_png):
    """items: [(name, path)] -> shelf-pack, returns {name: {x,y,width,height}}"""
    ims = [(n, Image.open(os.path.join(ROOT, p)).convert("RGBA")) for n, p in items]
    ims.sort(key=lambda t: -t[1].height)
    x = y = row_h = 0; placed = {}; W = 0
    for n, im in ims:
        w, h = im.width + 2 * GUTTER, im.height + 2 * GUTTER
        if x + w > max_w: x, y, row_h = 0, y + row_h, 0
        placed[n] = (x, y, im); x += w; row_h = max(row_h, h); W = max(W, x)
    H = y + row_h
    sheet = Image.new("RGBA", (W, H), (0, 0, 0, 0)); data = {}
    for n, (px, py, im) in placed.items():
        sheet.paste(extrude(im), (px, py))
        data[n] = {"x": px + GUTTER, "y": py + GUTTER, "width": im.width, "height": im.height}
    sheet.save(os.path.join(ROOT, out_png), optimize=True)
    print(out_png, sheet.size, os.path.getsize(os.path.join(ROOT, out_png)) // 1024, "KB")
    return data

# flag names must match countriesList in src/assets.js
flags = sorted(f[:-4] for f in os.listdir(os.path.join(ROOT, "sprites"))
               if f.endswith(".png") and os.path.exists(os.path.join(ROOT, "sprites", f))
               and Image.open(os.path.join(ROOT, "sprites", f)).size in {(48, 48), (47, 47)})
flags_data = pack([(n, f"sprites/{n}.png") for n in flags], 416, "sprites/atlas_flags.png")
misc = {"coin": "coin.png", "golden_ball": "golden_ball.png", "ball": "ball.png",
        "slide_icon": "slide_icon.png", "bicycle_kick": "bycycle_kick.png"}
misc_data = pack([(n, f"sprites/{p}") for n, p in misc.items()], 1024, "sprites/atlas_misc.png")

with open(os.path.join(ROOT, "src", "atlas_data.js"), "w") as f:
    f.write("// GENERATED by tools/build_atlases.py - do not edit by hand.\n")
    f.write("export const FLAGS_ATLAS = " + json.dumps(flags_data, indent=1) + ";\n")
    f.write("export const MISC_ATLAS = " + json.dumps(misc_data, indent=1) + ";\n")
